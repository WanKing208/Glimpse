GeoPoint? geoForName(String name) {
  final lower = name.toLowerCase();

  // 1) 中文/长关键字直接包含匹配（按长度倒序，避免短词抢匹配）
  final cjkKeys = _regions.keys.where((k) => !_isAscii(k)).toList()
    ..sort((a, b) => b.length.compareTo(a.length));
  for (final k in cjkKeys) {
    if (name.contains(k)) {
      final v = _regions[k]!;
      return GeoPoint(v.$1, v.$2, v.$3);
    }
  }

  // 2) 英文：按分隔符切词，整词匹配（支持 hk-01、us2、japan 等写法）
  final tokens = lower.split(RegExp(r'[^a-z0-9]+'));
  final asciiKeys = _regions.keys.where(_isAscii).toList()
    ..sort((a, b) => b.length.compareTo(a.length));
  for (final token in tokens) {
    if (token.isEmpty) continue;
    for (final k in asciiKeys) {
      if (token == k || token == '${k}1' || token.startsWith('$k-')) {
        final v = _regions[k]!;
        return GeoPoint(v.$1, v.$2, v.$3);
      }
    }
  }
  // 3) 退化为包含匹配（长度 >= 3 的英文关键字）
  for (final k in asciiKeys) {
    if (k.length >= 3 && lower.contains(k)) {
      final v = _regions[k]!;
      return GeoPoint(v.$1, v.$2, v.$3);
    }
  }
  return null;
}

bool _isAscii(String s) => s.codeUnits.every((c) => c < 128);
